#!/usr/bin/env python3
"""Write src/scyllasband_text_data.inc from scyllasband/text_data/*.json, so the C++ text normalizer reads the same tables.

    python libscyllasband/tools/generate_text_data.py [--check]

Each file is embedded as written and parsed once at first use: a new term needs this script run again, not a code change.
--check exits non-zero when the committed file differs from what this script would write.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from scyllasband.text_data import DATA_DIR, LANGUAGES  # noqa: E402

OUT = ROOT / "libscyllasband" / "src" / "scyllasband_text_data.inc"
# Each file is split at line ends into string literals of at most this many bytes (MSVC limits one literal to 16 KB).
PIECE_BYTES = 4000
DELIMITER = "json"


def pieces(text: str) -> list[str]:
    out, piece = [], ""
    for line in text.splitlines(keepends=True):
        if piece and len((piece + line).encode("utf-8")) > PIECE_BYTES:
            out.append(piece)
            piece = ""
        piece += line
    out.append(piece)
    return out


def render() -> str:
    lines = ["// Generated by tools/generate_text_data.py from scyllasband/text_data/*.json. Do not edit.",
             "struct TextDataFile {", "    const char* language;", "    const char* json;", "};",
             "static const TextDataFile kTextData[] = {"]
    for language in LANGUAGES:
        text = (DATA_DIR / f"{language}.json").read_text(encoding="utf-8")
        if f"){DELIMITER}\"" in text:
            raise ValueError(f"{language}.json contains the raw string delimiter")
        lines.append(f'    {{"{language}",')
        lines.extend(f'R"{DELIMITER}({piece}){DELIMITER}"' for piece in pieces(text))
        lines[-1] += "},"
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date; run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
