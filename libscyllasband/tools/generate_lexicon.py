#!/usr/bin/env python3
"""Write src/scyllasband_lexicon.inc from scyllasband/lexicon.py, so the C++ runtime embeds the same lexicon.

    python libscyllasband/tools/generate_lexicon.py [--check]

--check exits non-zero when the committed file differs from what this script would write.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from scyllasband.lexicon import INITIALISMS, LETTERS, PLURAL_PHONE, PLURAL_SUFFIXES, WORDS, initialism_phones  # noqa: E402

OUT = ROOT / "libscyllasband" / "src" / "scyllasband_lexicon.inc"


def literal(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render() -> str:
    lines = ["// Generated by tools/generate_lexicon.py from scyllasband/lexicon.py. Do not edit.",
             "struct LexiconEntry {", "    const char* language;", "    const char* word;", "    const char* phones;", "};",
             "static const LexiconEntry kLexiconInitialisms[] = {"]
    for language, letters in LETTERS.items():
        for word in INITIALISMS.get(language, ()):
            lines.append(f"    {{{literal(language)}, {literal(word)}, {literal(initialism_phones(word, letters))}}},")
    lines += ["};", "static const LexiconEntry kLexiconWords[] = {"]
    for language, entries in WORDS.items():
        for word, phones in entries.items():
            lines.append(f"    {{{literal(language)}, {literal(word)}, {literal(phones)}}},")
    lines += ["};", "static const char* const kLexiconPluralSuffixes[] = {" + ", ".join(literal(s) for s in PLURAL_SUFFIXES) + "};",
              f"static const char* const kLexiconPluralPhone = {literal(PLURAL_PHONE)};", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date; run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
